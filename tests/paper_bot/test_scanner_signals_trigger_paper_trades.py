"""
Targeted regression test: Verify Scanner signals successfully trigger Paper trades.

Traces the entire pipeline:
  Signal generated by Scanner -> Signal saved in Scanner DB -> Paper reads signal
  -> Signal accepted by QPB -> Risk checks pass -> Paper order executed -> Position persisted in Paper DB.
"""

from __future__ import annotations

import asyncio
import tempfile
import uuid
from datetime import datetime, timezone, timedelta
from pathlib import Path

import pytest

from core.bus import bus
from core.config import get_config
from core.repository.db import Database
from core.repository.position_repo import PositionRepository
from core.repository.qpb_repo import QPBRepository
from core.repository.signal_repo import SignalRepository
from core.repository.trade_repo import TradeRepository
from core.types import BotMode, MarketState, OppType, Priority, RiskLevel, Signal
from execution.auto_trader import AutoTradeRouter
from execution.position_manager import PositionManager
from execution.risk.capital_guard import CapitalGuard
from paper.execution.router import PaperExecutionRouter
from paper.portfolio import QPBPortfolioService


@pytest.mark.asyncio
async def test_scanner_signal_triggers_paper_position_end_to_end():
    # 1. Setup isolated Scanner DB and Paper DB
    temp_dir = Path(tempfile.mkdtemp())
    scanner_db_path = temp_dir / "test_scanner.db"
    paper_db_path = temp_dir / "test_paper.db"

    scanner_db = Database(str(scanner_db_path))
    await scanner_db.open()
    paper_db = Database(str(paper_db_path))
    await paper_db.open()

    scanner_signal_repo = SignalRepository(scanner_db.connection)
    position_repo = PositionRepository(paper_db.connection)
    trade_repo = TradeRepository(paper_db.connection)
    qpb_repo = QPBRepository(paper_db.connection)

    app_config = get_config()
    app_config.deployment_mode = "PAPER"
    app_config.db_path = str(paper_db_path)

    # 2. Setup Paper Trading components
    auto_trader = AutoTradeRouter(
        bus=bus,
        dry_run=True,
        position_repo=position_repo,
    )
    position_manager = PositionManager(
        position_repo=position_repo,
        trade_repo=trade_repo,
        bus=bus,
    )
    capital_guard = CapitalGuard(app_config)
    paper_router = PaperExecutionRouter(
        bus=bus,
        auto_trader=auto_trader,
        position_manager=position_manager,
        capital_guard=capital_guard,
        position_repo=position_repo,
    )
    qpb_service = QPBPortfolioService(
        config=app_config,
        qpb_repo=qpb_repo,
        position_repo=position_repo,
        trade_repo=trade_repo,
        execution_router=paper_router,
    )

    now = datetime.now(timezone.utc)
    entry_price = 100000.0
    # Simulate realistic Scanner candidate calculation (standard conviction: score < 90)
    score = 86.0
    bot = "HDA"
    atr_pct = 2.5
    sl_pct = min(7.5, max(4.5, atr_pct * 1.8))  # 4.5%
    tp_pct = 5.0
    # Scanner R:R calibration fix ensures tp_pct >= sl_pct * 1.25
    min_tp_for_rr = round(sl_pct * 1.25, 2)
    if tp_pct < min_tp_for_rr:
        tp_pct = min_tp_for_rr

    stop_loss = round(entry_price * (1.0 - sl_pct / 100.0), 4)
    take_profit = round(entry_price * (1.0 + tp_pct / 100.0), 4)
    rr = (take_profit - entry_price) / (entry_price - stop_loss)
    assert rr >= 1.20, f"Signal risk/reward {rr:.3f} must satisfy QPB minimum 1.20"

    cand_payload = {
        "coin": "ETH",
        "pair": "ETH/INR",
        "score": score,
        "composite_score": score,
        "price": entry_price,
        "entry_price": entry_price,
        "stop_loss": stop_loss,
        "take_profit": take_profit,
        "sl_pct": sl_pct,
        "tp_pct": tp_pct,
        "signal_reason": "High Momentum Divergence: continuation",
        "indicators": {
            "rsi": 58.0,
            "atr_pct": atr_pct,
            "volume_24h": 500000.0,
            "volume_ratio": 1.5,
            "mtf_aligned": True,
        },
        "priority": "High",
        "strategy": bot,
        "bot": bot,
        "strategy_name": "High Momentum Divergence",
        "timeframe": "1h",
        "ttl_seconds": 300,
        "market_state": "BULL_TREND",
        "opportunity_type": "continuation",
        "timestamp": now.isoformat(),
        "generated_at": now.isoformat(),
        "expires_at": (now + timedelta(seconds=300)).isoformat(),
    }

    sig = Signal(
        id=f"sig_{uuid.uuid4().hex[:8]}",
        coin="ETH",
        pair="ETH/INR",
        market_state=MarketState.BULL_TREND,
        opportunity_type=OppType.MOMENTUM_TRADE,
        priority=Priority.HIGH,
        risk_level=RiskLevel.LOW,
        score=score,
        confidence=82.0,
        coin_class="A",
        mtf_alignment=True,
        generated_at=now,
        expires_at=now + timedelta(seconds=300),
        source_bot=bot,
        raw_payload=cand_payload,
    )

    # 3. Scanner saves signal into Scanner DB
    await scanner_signal_repo.insert(sig)
    saved_sig = await scanner_signal_repo.get_by_id(sig.id)
    assert saved_sig is not None, "Signal must be saved in Scanner DB"

    # 4. Paper reads live signals from Scanner DB via read-only connection
    paper_scanner_db = Database(str(scanner_db_path), read_only=True)
    await paper_scanner_db.open()
    paper_signal_intake_repo = SignalRepository(paper_scanner_db.connection)

    live_signals = await paper_signal_intake_repo.get_live(grace_period_seconds=15.0)
    assert len(live_signals) == 1, "Paper must read live signal from Scanner DB"
    intake_sig = live_signals[0]
    assert intake_sig.id == sig.id

    # 5. Paper QPB processes signals
    results = await qpb_service.process_signals([intake_sig])
    assert len(results) == 1, "QPB must evaluate signal"
    decision = results[0]
    assert decision["success"] is True, f"QPB execution failed: {decision}"
    assert decision["code"] == "EXECUTED", f"Expected EXECUTED, got {decision}"
    assert decision.get("position_id") is not None, "Decision must return created position_id"

    # 6. Verify Position was actually created and persisted in Paper DB
    open_positions = await position_repo.get_open(mode=BotMode.PAPER)
    assert len(open_positions) == 1, "Exactly 1 Paper position must be opened"
    persisted_pos = open_positions[0]
    assert persisted_pos.signal_id == sig.id
    assert persisted_pos.coin == "ETH"
    assert persisted_pos.mode == BotMode.PAPER
    assert persisted_pos.entry_price == entry_price
    assert persisted_pos.stop_loss == stop_loss
    assert persisted_pos.take_profit == take_profit
    assert persisted_pos.qty > 0.0

    # 7. Verify Deduplication: Re-processing identical signal must reject with DUPLICATE_SIGNAL
    dedup_results = await qpb_service.process_signals([intake_sig])
    assert len(dedup_results) == 1
    assert dedup_results[0]["success"] is False
    assert dedup_results[0]["code"] == "DUPLICATE_SIGNAL"
    positions_after_dedup = await position_repo.get_open(mode=BotMode.PAPER)
    assert len(positions_after_dedup) == 1, "No duplicate position should be created"

    # 8. Verify Crash Recovery: If a signal was left in unfinalized state ('RECEIVED') without a position
    crashed_sig_id = f"crashed_{uuid.uuid4().hex[:8]}"
    await qpb_repo.claim(crashed_sig_id, {"coin": "SOL", "symbol": "SOL", "strategy": "STE"})
    crashed_decision = await qpb_repo.get(crashed_sig_id)
    assert crashed_decision["status"] == "RECEIVED"

    # Next evaluation cleanly cleans up unfinalized decision to REJECTED (INTERRUPTED_CYCLE)
    recovery_payload = {"signal_id": crashed_sig_id, "coin": "SOL", "symbol": "SOL", "strategy": "STE"}
    rec_results = await qpb_service.process_signals([recovery_payload])
    assert rec_results[0]["code"] == "DUPLICATE_SIGNAL"
    updated_decision = await qpb_repo.get(crashed_sig_id)
    assert updated_decision["status"] == "REJECTED"
    assert updated_decision["reason_code"] == "INTERRUPTED_CYCLE"

    # 9. Cleanup
    await scanner_db.close()
    await paper_scanner_db.close()
    await paper_db.close()
